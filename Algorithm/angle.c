// ma_raw 方向校准 ma_dirfixed
void angleDf_float_fix(float* a_df, int8_t direction, float a_cs)
{		
	if (direction == 1)
	{
		*a_df = a_cs;
	}
	else if(direction == -1)
	{
		*a_df = 360.0f - a_cs;
	}
}

// 零点校准 ma0
void angleZero_float_get(float* a_zero, int8_t direction)
{
	float a;
	
	delay_1ms(10);
	motor_to_eangle(0u);
	delay_1ms(600);

	angleCs_float_fromEncoder(&a);
	angleDf_float_fix(&a, direction, a);
	
	*a_zero = a;
	
	while(1)
	{
		delay_1ms(10);
		spi0_ATK_16bit(a);
	}
}




